    private string _language = Chinese;

    private Localization()
    {
    }

    public static Localization Instance { get; } = new();

    public event PropertyChangedEventHandler? PropertyChanged;
    public event Action? LanguageChanged;

    public string Language
    {
        get => _language;
        set
        {
            var normalized = value is English ? English : Chinese;
            if (_language == normalized)
                return;
            _language = normalized;
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
            LanguageChanged?.Invoke();
        }
    }

    public bool IsEnglish => _language == English;

    public string this[string key] => Get(key);

    public static string T(string key)
    {
        return Instance.Get(key);
    }

    public static string T(string key, params object?[] args)
    {
        return Instance.Get(key, args);
    }

    public string Get(string key, params object?[] args)
    {
        var table = _language == English ? En : Zh;
        if (!table.TryGetValue(key, out var text))
            text = Zh.TryGetValue(key, out var zh) ? zh : key;
        return args.Length > 0 ? string.Format(text, args) : text;
    }
